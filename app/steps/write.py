"""Step 5 — WRITE. Gemini drafts the underwriter credit memo; Python renders it."""

from __future__ import annotations

import markdown as md

from app.config import settings
from app.gemini_client import GeminiStepFailure, gemini, load_prompt, render
from app.guardrail import allowed_numbers, check_payload
from app.schemas import Assessment, CreditMemo, EvidenceItem, GuardrailReport, StepTrace, WriteResult
from app.steps.explain import score_payload, sims_payload, verification_payload
from app.steps.verify import _doc_summary


def build_evidence(a: Assessment) -> list[dict]:
    """Every figure the memo may cite, with its source pointer."""
    ev: list[dict] = []
    for r in a.reads:
        for f in r.result.monthly_figures:
            label = {"bank_statement": "Bank inflows", "sales_ledger": "Ledger sales", "payment_export": "Payment settlements"}.get(r.result.document_type, "Figure")
            ev.append({"figure": f"{label} {f.month}", "value": f"₮{f.sales_or_inflows_mnt:,.0f}", "source": f"{r.filename}, {f.page_or_row}"})
        for e in r.result.extracted_fields:
            ev.append({"figure": e.field.replace("_", " "), "value": e.value, "source": f"{r.filename}, {e.page_or_row} (confidence {e.confidence:.2f})"})
    m = a.verify.metrics if a.verify else {}
    bank_files = ", ".join(r.filename for r in a.reads if r.result.document_type == "bank_statement") or "documents"
    if m:
        ev.append({"figure": "Average monthly inflows", "value": f"₮{m.get('avg_monthly_inflow_mnt', 0):,.0f}", "source": f"computed from {bank_files}"})
        ev.append({"figure": "Months documented", "value": str(m.get("months_documented")), "source": f"computed from {bank_files}"})
        ev.append({"figure": "Inflow coefficient of variation", "value": str(m.get("inflow_cv")), "source": f"computed from {bank_files}"})
    d = a.declared
    ev.append({"figure": "Declared monthly revenue", "value": f"₮{d.monthly_revenue_mnt:,.0f}", "source": "loan application form"})
    ev.append({"figure": "Requested amount", "value": f"₮{d.loan_amount_mnt:,.0f} over {d.tenor_months} months", "source": "loan application form"})
    ev.append({"figure": "Declared years in business", "value": f"{d.years_in_business:g}", "source": "loan application form"})
    return ev


def render_markdown(memo: CreditMemo, a: Assessment) -> str:
    s = a.score
    lines = [
        f"# {memo.title}",
        "",
        "*Draft for human underwriting review · generated by Kervan Credit Passport*",
        "",
        "## 1. Business summary",
        memo.business_summary,
        "",
        "## 2. Cash-flow analysis",
        memo.cash_flow_analysis,
        "",
        "## 3. Verification status",
        memo.verification_status,
        "",
        "## 4. Key risks",
        *[f"- {r}" for r in memo.key_risks],
        "",
        "## 5. Mitigants",
        *[f"- {m_}" for m_ in memo.mitigants],
        "",
        "## 6. Scorecard result (deterministic)",
        memo.scorecard_result,
        "",
    ]
    if s:
        lines += [
            "| Factor | Value | Points | Max | Status |",
            "|---|---|---:|---:|---|",
            *[f"| {f.label} | {f.raw_display} | {f.points:g} | {f.max_points:g} | {f.verification_status.replace('_', ' ')} |" for f in s.factors],
            *[f"| Penalty: {p.code} | {p.detail} | {p.points:g} | | |" for p in s.penalties],
            f"| **Total** | | **{s.total_points:g}** | **{s.max_points:g}** | grade **{s.grade}** ({s.grade_label}) |",
            "",
            f"PD estimate {s.pd_illustrative:.1%} · rate band {s.rate_band} · scorecard `{s.scorecard_version}`",
            "",
        ]
    lines += [
        "## 7. Suggested limit and tenor",
        memo.suggested_limit_and_tenor,
        "",
        "## Appendix — Evidence trail",
        "| Figure | Value | Source |",
        "|---|---|---|",
        *[f"| {e.figure} | {e.value} | {e.source} |" for e in memo.evidence_appendix],
        "",
    ]
    return "\n".join(lines)


def to_html(markdown_text: str) -> str:
    return md.markdown(markdown_text, extensions=["tables"])


async def write_memo(a: Assessment) -> tuple[WriteResult, StepTrace]:
    assert a.score and a.verify
    evidence = build_evidence(a)
    template, version = load_prompt("write")
    declared = a.declared.model_dump()
    declared.pop("owner_name", None)
    documents = [_doc_summary(r) for r in a.reads]
    v_payload = verification_payload(a.verify, limit=30)
    v_payload["notes"] = a.verify.llm_notes
    s_payload = score_payload(a.score)
    sim_payload = sims_payload(a.simulations)
    prompt = render(template, declared=declared, documents=documents, verification=v_payload, score=s_payload, simulations=sim_payload, evidence=evidence)
    allowed = allowed_numbers({"declared": declared, "documents": documents, "verification": v_payload, "score": s_payload, "sims": sim_payload, "evidence": evidence, "metrics": a.verify.metrics})

    if settings.offline:
        from app import offline

        memo, trace = offline.write(a.declared, a.score, a.verify, evidence, version)
        guardrail = GuardrailReport(note="offline fixture")
    else:
        guardrail = GuardrailReport()
        try:
            memo, trace = await gemini.generate_json(
                step="write", prompt_name="write", prompt_version=version, prompt_text=prompt,
                schema=CreditMemo, input_refs=[r.filename for r in a.reads] + ["verification", "score"], temperature=0.3,
            )
            checked, violations = check_payload(memo.model_dump(), allowed)
            guardrail.numbers_checked = checked
            if violations:
                retry_prompt = prompt + (
                    "\n\nGUARDRAIL VIOLATION in your previous draft: these numbers do not exist in the inputs: "
                    + ", ".join(violations[:12]) + ". Rewrite the memo using only figures given above."
                )
                memo2, trace2 = await gemini.generate_json(
                    step="write", prompt_name="write", prompt_version=version, prompt_text=retry_prompt,
                    schema=CreditMemo, input_refs=[r.filename for r in a.reads], temperature=0.2, use_cache=False,
                )
                trace.attempts += trace2.attempts
                trace.latency_ms += trace2.latency_ms
                checked2, violations2 = check_payload(memo2.model_dump(), allowed)
                guardrail.numbers_checked = checked2
                if len(violations2) <= len(violations):
                    memo = memo2
                guardrail.violations = violations2 if len(violations2) <= len(violations) else violations
                guardrail.note = ("Retry removed invented numbers" if not guardrail.violations else
                                  f"{len(guardrail.violations)} number(s) could not be traced to inputs; shown for underwriter attention")
                trace.note = guardrail.note
            else:
                guardrail.note = "All numbers in the memo exist in the inputs"
        except GeminiStepFailure as exc:
            from app import offline

            trace = exc.trace
            trace.note = "Gemini unavailable; template memo used"
            memo, _ = offline.write(a.declared, a.score, a.verify, evidence, version)
            guardrail = GuardrailReport(fallback_used=True, note="Gemini call failed; deterministic template memo")

    if len(memo.evidence_appendix) < 6:
        memo.evidence_appendix += [EvidenceItem(**e) for e in evidence[-6:]]
    markdown_text = render_markdown(memo, a)
    return WriteResult(memo=memo, markdown=markdown_text, html=to_html(markdown_text), guardrail=guardrail), trace
